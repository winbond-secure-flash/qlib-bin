/* Calculate alignment of address (1, 2 or 4)                                                              */
/*---------------------------------------------------------------------------------------------------------*/
#define ALIGNMENT(a) (((((uintptr_t)(a)) % 4u) == 1u) ? 1u : (4u - (((uintptr_t)(a)) % 4u)))

