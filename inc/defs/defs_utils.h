/*---------------------------------------------------------------------------------------------------------*/
/* Busy wait with Timeout and custom error action                                                          */
/*---------------------------------------------------------------------------------------------------------*/
#define BUSY_WAIT_TIMEOUT_ERROR_ACTION(busy_cond, timeout, errAction) \
    {                                                                 \
        uint32_t __time = timeout;                                    \
                                                                      \
        do                                                            \
        {                                                             \
            if (__time-- == 0u)                                       \
            {                                                         \
                errAction;                                            \
            }                                                         \
        } while (busy_cond);                                          \
    }

/*---------------------------------------------------------------------------------------------------------*/
