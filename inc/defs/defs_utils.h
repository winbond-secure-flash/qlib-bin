/*---------------------------------------------------------------------------------------------------------*/
/* Swap high byte and low byte                                                                             */
/*                                                                                                         */
/* SWAP16 operation example:                                                                               */
/* 16bit source: <byte2><byte1>                                                                            */
/* 16bit result: <byte1><byte2>                                                                            */
/*                                                                                                         */
/*---------------------------------------------------------------------------------------------------------*/
#define SWAP16(u16) (((uint16_t)((u16)&0x00FFu) << 8) | (((uint16_t)(u16)&0xFF00u) >> 8))

/*---------------------------------------------------------------------------------------------------------*/
/* Swap high word and low word                                                                             */
/*                                                                                                         */
/* SWAP32 operation example:                                                                               */
/* 32bit source: <word2><word1>                                                                            */
/* 32bit result: <word1><word2>                                                                            */
/*                                                                                                         */
/*---------------------------------------------------------------------------------------------------------*/
#define SWAP32(u32) (((uint32_t)((u32)&0x0000FFFFu) << 16) | (((uint32_t)(u32)&0xFFFF0000u) >> 16))

/*---------------------------------------------------------------------------------------------------------*/
/* Swap high dword and low dword                                                                           */
/*                                                                                                         */
/* SWAP64 operation example:                                                                               */
/* 64bit source: <dword2><dword1>                                                                          */
/* 64bit result: <dword1><dword2>                                                                          */
/*                                                                                                         */
/*---------------------------------------------------------------------------------------------------------*/
#define SWAP64(u64) (((uint64_t)((u64)&0x00000000FFFFFFFFu) << 32) | (((uint64_t)(u64)&0xFFFFFFFF00000000u) >> 32))

/*---------------------------------------------------------------------------------------------------------*/
/* Make 8-bit value from 2 nibble values                                                                   */
/*                                                                                                         */
/* MAKE8 operation example:                                                                                */
/* Two 4bit sources: <nibble1>, <nibble2>                                                                  */
/* 8bit result:     <nibble2><nibble1>                                                                     */
/*                                                                                                         */
/*---------------------------------------------------------------------------------------------------------*/
#define MAKE8(nlo, nhi) ((uint8_t)(((uint8_t)(nlo)) | (((uint8_t)(nhi)) << 4)))

/*---------------------------------------------------------------------------------------------------------*/
/* Make 16-bit value from 2 byte values                                                                    */
/*                                                                                                         */
/* MAKE16 operation example:                                                                               */
/* Two 8bit sources: <byte1>, <byte2>                                                                      */
/* 16bit result:     <byte2><byte1>                                                                        */
/*                                                                                                         */
/*---------------------------------------------------------------------------------------------------------*/
#define MAKE16(blo, bhi) ((uint16_t)(((uint16_t)(blo)) | (((uint16_t)(bhi)) << 8)))

/*---------------------------------------------------------------------------------------------------------*/
/* Make 32-bit value from 2 word values                                                                    */
/*                                                                                                         */
/* MAKE32 operation example:                                                                               */
/* Two 16bit sources: <word1>, <word2>                                                                     */
/* 32bit result:      <word2><word1>                                                                       */
/*                                                                                                         */
/*---------------------------------------------------------------------------------------------------------*/
#define MAKE32(wlo, whi) ((uint32_t)(((uint32_t)(wlo)) | (((uint32_t)(whi)) << 16)))

/*---------------------------------------------------------------------------------------------------------*/
/* Make 32-bit value from 4 bytes                                                                          */
/*                                                                                                         */
/* MAKE32B operation example:                                                                              */
/* Four 8bit sources: <byte0>, <byte1>, <byte2>, <byte3>                                                   */
/* 32bit result:      <byte3><byte2><byte1><byte0>                                                         */
/*                                                                                                         */
/*---------------------------------------------------------------------------------------------------------*/
#define MAKE32B(b0, b1, b2, b3) MAKE32(MAKE16(b0, b1), MAKE16(b2, b3))

/*---------------------------------------------------------------------------------------------------------*/
/* Make 64-bit value from 2 word values                                                                    */
/*                                                                                                         */
/* MAKE64 operation example:                                                                               */
/* Two 16bit sources: <word1>, <word2>                                                                     */
/* 32bit result:      <word2><word1>                                                                       */
/*                                                                                                         */
/*---------------------------------------------------------------------------------------------------------*/
#define MAKE64(dwlo, dwhi) ((uint64_t)(((uint64_t)(dwlo)) | (((uint64_t)(dwhi)) << 32)))

/*---------------------------------------------------------------------------------------------------------*/
/* Make 64-bit value from 8 bytes                                                                          */
/*                                                                                                         */
/* MAKE64B operation example:                                                                              */
/* Eight 8bit sources:  <byte0>, <byte1>, <byte2>, <byte3>, <byte4>, <byte5>, <byte6>, <byte7>             */
/* 32bit result:        <byte7><byte6><byte5><byte4><byte3><byte2><byte1><byte0>                           */
/*                                                                                                         */
/*---------------------------------------------------------------------------------------------------------*/
#define MAKE64B(b0, b1, b2, b3, b4, b5, b6, b7) \
    MAKE64(MAKE32(MAKE16(b0, b1), MAKE16(b2, b3)), MAKE32(MAKE16(b4, b5), MAKE16(b6, b7)))

/*---------------------------------------------------------------------------------------------------------*/
/* Big to Little endian converter - 16 bit                                                                 */
/*                                                                                                         */
/* LE16 operation example:                                                                                 */
/* 16bit source: <byte2><byte1>                                                                            */
/* 16bit result: <byte1><byte2>                                                                            */
/*                                                                                                         */
/*---------------------------------------------------------------------------------------------------------*/
#ifndef LE16
#define LE16(u16) (((uint16_t)((u16)&0xFFu) << 8) | (((uint16_t)(u16)&0xFF00u) >> 8))
#endif

/*---------------------------------------------------------------------------------------------------------*/
/* Big to Little endian converter - 32 bit                                                                 */
/*                                                                                                         */
/* LE32 operation example:                                                                                 */
/* 32bit source: <byte4><byte3><byte2><byte1>                                                              */
/* 32bit result: <byte1><byte2><byte3><byte4>                                                              */
/*                                                                                                         */
/*---------------------------------------------------------------------------------------------------------*/
#ifndef LE32
#define LE32(u32)                                                                                              \
    (((uint32_t)((u32)&0xFFu) << 24) | ((uint32_t)((u32)&0xFF00u) << 8) | (((uint32_t)(u32)&0xFF0000u) >> 8) | \
     (((uint32_t)(u32)&0xFF000000u) >> 24))
#endif

/*---------------------------------------------------------------------------------------------------------*/
/* Big to Little endian converter - 64 bit                                                                 */
/*                                                                                                         */
/* LE32 operation example:                                                                                 */
/* 32bit source: <byte8><byte7><byte6><byte5><byte4><byte3><byte2><byte1>                                  */
/* 32bit result: <byte1><byte2><byte3><byte4><byte5><byte6><byte7><byte8>                                  */
/*                                                                                                         */
/*---------------------------------------------------------------------------------------------------------*/
#ifndef LE64
#define LE64(u64) MAKE64(LE32(MS32(u64)), LE32(LS32(u64)))
#endif

/*---------------------------------------------------------------------------------------------------------*/
/* Big to Little endian converter - Array                                                                  */
/*---------------------------------------------------------------------------------------------------------*/
#define LE_ARRAY(out, in, byteSize)                                         \
    {                                                                       \
        uint32_t i_ = 0;                                                    \
                                                                            \
        for (i_ = 0; i_ < (byteSize); ++i_)                                 \
        {                                                                   \
            ((uint8_t*)(out))[i_] = ((uint8_t*)(in))[((byteSize)-i_) - 1u]; \
        }                                                                   \
    }

/*---------------------------------------------------------------------------------------------------------*/
/* Extracting Nibble - 4 bit: MSN, LSN                                                                     */
/*---------------------------------------------------------------------------------------------------------*/
#define MS4(u8) ((uint8_t)((uint8_t)(u8) >> 4))
#define LS4(u8) ((uint8_t)((uint8_t)(u8)&0x0Fu))

/*---------------------------------------------------------------------------------------------------------*/
/* Extracting Byte - 8 bit: MSB, LSB                                                                       */
/*---------------------------------------------------------------------------------------------------------*/
#define MS8(u16) ((uint8_t)((uint16_t)(u16) >> 8))
#define LS8(u16) ((uint8_t)((u16)&0xFFu))

/*---------------------------------------------------------------------------------------------------------*/
/* Extracting Word - 16 bit: MSW, LSW                                                                      */
/*---------------------------------------------------------------------------------------------------------*/
#define MS16(u32) ((uint16_t)((uint32_t)(u32) >> 16))
#define LS16(u32) ((uint16_t)((u32)&0xFFFFu))

/*---------------------------------------------------------------------------------------------------------*/
/* Extracting DWord - 32 bit: MSDW, LSDW                                                                   */
/*---------------------------------------------------------------------------------------------------------*/
#define MS32(u64) ((uint32_t)((uint64_t)(u64) >> 32))
#define LS32(u64) ((uint32_t)((u64)&0xFFFFFFFFu))

/*---------------------------------------------------------------------------------------------------------*/
/* Extracting bytes                                                                                        */
/*---------------------------------------------------------------------------------------------------------*/
#define LSBx(u, x) ((uint8_t)((sizeof(u) > (x)) ? (uint8_t)(((u) >> ((x)*8u)) & 0xFFu) : (uint8_t)0u))

#define LSB0(u) LSBx(u, 0u)
#define LSB1(u) LSBx(u, 1u)
#define LSB2(u) LSBx(u, 2u)
#define LSB3(u) LSBx(u, 3u)
#define LSB4(u) LSBx(u, 4u)
#define LSB5(u) LSBx(u, 5u)
#define LSB6(u) LSBx(u, 6u)
#define LSB7(u) LSBx(u, 7u)

/*---------------------------------------------------------------------------------------------------------*/
/* Extracting bits                                                                                         */
/*---------------------------------------------------------------------------------------------------------*/
#define BITx(u, x)           (((u) >> (x)) & 0x1U)
#define BITS(u, start, size) (((u) >> (start)) & BUILD_FIELD_MASK(size, 0u))

/*---------------------------------------------------------------------------------------------------------*/
/* Bits <-> Bytes conversion                                                                               */
/*---------------------------------------------------------------------------------------------------------*/
#define BITS_TO_BYTES(bits)  ((bits) / 8u)
#define BYTES_TO_BITS(bytes) ((bytes)*8u)

