/*---------------------------------------------------------------------------------------------------------*/
/* Round (down) the number(val)on the (n) boundary.  (n) must be power of 2                                */
/*---------------------------------------------------------------------------------------------------------*/
// double xor is used to promote (n-1) to the same type of val without affecting its value
#define ROUND_DOWN(val, n) ((val) & (~(((n)-1u) ^ (val) ^ (val))))

/*---------------------------------------------------------------------------------------------------------*/
/* Round (up) the number (val) on the (n) boundary.  (n) must be power of 2                                */
/*---------------------------------------------------------------------------------------------------------*/
#define ROUND_UP(val, n) ROUND_DOWN((((val) + (n)) - 1u), (n))

/*---------------------------------------------------------------------------------------------------------*/
/* Log2 of a number to return the number of bits needed to represent it                                    */
/*---------------------------------------------------------------------------------------------------------*/
#define LOG2(n) ((((n) & ((n)-1u)) == 0u) ? (LOG_16_(n)) : (LOG_16_(n) + 1u))

