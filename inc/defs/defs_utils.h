/*---------------------------------------------------------------------------------------------------------*/
/* Check if parameter is aligned to selected value (val should be a power of 2)                            */
/*---------------------------------------------------------------------------------------------------------*/
// double xor is used to promote (val-1) to the same type as x without affecting its value
#define ALIGNED_TO(x, val) (((x) & (~(((val)-1u) ^ (x) ^ (x)))) == (x))

